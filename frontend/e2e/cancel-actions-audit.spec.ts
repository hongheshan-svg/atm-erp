import { test, expect, authenticate, login, openRowAction, submitDialog, type Page } from './fixtures'

const dialog = (page: Page) => page.getByRole('dialog')
const row = (page: Page, value: string) => page.locator('.el-table__body tr:visible').filter({ hasText: value }).first()
async function projectAction(page: Page, name: string) {
  await page.getByRole('button', { name: '项目操作 ▾', exact: true }).click()
  await page.getByRole('menuitem', { name, exact: true }).click()
}
const reason = (page: Page) => dialog(page).getByLabel('原因 / 说明', { exact: true })

test('销售经理从工作台进入销售列表并取消草稿，保留原销售记录', async ({ page }, info) => {
  await login(page, 'admin', process.env.E2E_ADMIN_PASSWORD!)
  const admin = await authenticate(page.request, 'admin', process.env.E2E_ADMIN_PASSWORD!), suffix = `${Date.now()}-${info.project.name}`
  const password = 'Sales-cancel-audit-2026-only'
  const person = await admin.post('/api/auth/users/', { username: `cancel_sales_${Date.now()}`, display_name: '销售取消验收', roles: ['sales_manager'], password })
  const customer = await admin.post('/api/business/partners/', { name: `取消验收客户${suffix}`, kind: 'customer' })
  const created = await admin.post('/api/business/sales/', { name: `取消验收销售${suffix}`, customer: customer.id, manager: person.id })
  const sale = await admin.get(`/api/business/sales/${created.id}/`)
  await login(page, person.username, password)
  await page.evaluate(({ id }) => sessionStorage.setItem(`resource-search-${id}-sales-{}`, '旧搜索不应覆盖工作台入口'), { id: person.id })
  // 工作台不再逐条列出销售单，只保留「其他待办」入口；进入时必须清掉上次的搜索词，否则点进来是空列表。
  await page.getByRole('region', { name: '其他待办', exact: true }).getByRole('link', { name: '查看全部我的销售订单', exact: true }).click()
  await expect(page).toHaveURL(/\/erp\/sales\?search=$/)
  await expect(page.getByRole('searchbox', { name: '搜索销售订单', exact: true })).toHaveValue('')
  await expect(row(page, sale.name)).toBeVisible()
  await openRowAction(page, row(page, sale.name), '取消销售')
  await reason(page).fill('客户暂停需求，保留原销售草稿')
  await submitDialog(page, `business/sales/${sale.id}/cancel/`, 200)
  const cancelled = await admin.get(`/api/business/sales/${sale.id}/`)
  expect(cancelled).toMatchObject({ id: sale.id, name: sale.name, code: sale.code, status: 'cancelled', project: null })
  await expect(row(page, sale.name)).toContainText('已取消')
  await row(page, sale.name).getByRole('button', { name: '操作 ▾', exact: true }).click()
  await expect(page.getByRole('menuitem', { name: '取消销售', exact: true })).toHaveCount(0)
  await page.keyboard.press('Escape')
  await page.screenshot({ path: info.outputPath('cancelled-sale.png'), fullPage: true, animations: 'disabled' })
})

test('项目编辑取消重开、BOM移除及已付款费用取消均保留业务依据', async ({ page }, info) => {
  test.setTimeout(150000)
  await login(page, 'admin', process.env.E2E_ADMIN_PASSWORD!)
  const admin = await authenticate(page.request, 'admin', process.env.E2E_ADMIN_PASSWORD!), suffix = `${Date.now()}-${info.project.name}`
  const me = await admin.get('/api/auth/me/')
  const customer = await admin.post('/api/business/partners/', { name: `项目取消客户${suffix}`, kind: 'customer' })
  const created = await admin.post('/api/business/projects/', { name: `取消前项目${suffix}`, customer: customer.id, manager: me.id })
  const project = await admin.get(`/api/business/projects/${created.id}/`)
  const task = await admin.post('/api/business/tasks/', { project: project.id, title: `待办保留${suffix}`, kind: 'design', assignee: me.id })
  const material = await admin.post('/api/business/items/', { name: `移除BOM物料${suffix}`, unit: '件' })
  const originalDemand = await admin.get(`/api/business/projects/${project.id}/demand/`)
  await admin.post(`/api/business/projects/${project.id}/revise-bom/`, { expected_revision: originalDemand.revision, lines: [{ item: material.id, quantity: '2', change_note: '初版，用于验证移除保留依据', assembly_unit: '上料单元' }] }, 200)
  const bom = (await admin.get(`/api/business/bom/?project=${project.id}`)).results[0]

  await page.goto(`/erp/projects/${project.id}`)
  await projectAction(page, '编辑项目')
  await dialog(page).getByLabel('项目名称', { exact: true }).fill(`编辑后项目${suffix}`)
  await dialog(page).getByLabel('需求说明', { exact: true }).fill('设备名称按合同校对，单元方案变更')
  await reason(page).fill('校对项目名称与设备范围')
  await submitDialog(page, `business/projects/${project.id}/edit/`, 200)
  await expect(page.getByRole('heading', { level: 1 })).toHaveText(`编辑后项目${suffix}`)
  expect(await admin.get(`/api/business/projects/${project.id}/`)).toMatchObject({ id: project.id, code: project.code, requirements: '设备名称按合同校对，单元方案变更' })

  await page.goto(`/erp/projects/${project.id}?tab=bom`)
  await openRowAction(page, row(page, `移除BOM物料${suffix}`), '移除')
  const removeReason = `ECN移除未采购物料${suffix}`
  await reason(page).fill(removeReason)
  await submitDialog(page, `business/bom/${bom.id}/remove/`, 200)
  await expect(page.getByRole('region', { name: 'BOM 缺料需求', exact: true })).toContainText('尚未维护 BOM')
  expect((await admin.get(`/api/business/bom/?project=${project.id}`)).count).toBe(0)
  expect((await admin.get(`/api/business/projects/${project.id}/demand/`)).lines).toHaveLength(0)
  expect(await admin.get(`/api/business/items/${material.id}/`)).toMatchObject({ id: material.id, name: `移除BOM物料${suffix}` })
  const audit = await admin.get('/api/core/audit/?page_size=100')
  expect(audit.results.some((record: { operation: string; resource: string; detail: { reason?: string } }) => record.operation === 'bom.remove' && record.resource === `bomline:${bom.id}` && record.detail.reason === removeReason)).toBe(true)

  await projectAction(page, '取消项目')
  await reason(page).fill('现场计划暂停，待重新评估')
  await submitDialog(page, `business/projects/${project.id}/cancel/`, 200)
  expect(await admin.get(`/api/business/projects/${project.id}/`)).toMatchObject({ id: project.id, code: project.code, status: 'cancelled' })
  expect(await admin.get(`/api/business/tasks/${task.id}/`)).toMatchObject({ id: task.id, status: 'cancelled' })
  await projectAction(page, '重新打开')
  await reason(page).fill('客户确认恢复执行')
  await submitDialog(page, `business/projects/${project.id}/reopen/`, 200)
  expect(await admin.get(`/api/business/projects/${project.id}/`)).toMatchObject({ id: project.id, code: project.code, status: 'active' })
  expect(await admin.get(`/api/business/tasks/${task.id}/`)).toMatchObject({ id: task.id, status: 'cancelled' })

  const day = new Date().toLocaleDateString('sv-SE')
  const expense = await admin.post('/api/business/entries/expense/', { project: project.id, title: `取消已付款费用${suffix}`, amount: '50', due_date: day })
  const payment = await admin.post(`/api/business/entries/${expense.id}/pay/`, { amount: '50', date: day, reason: '已付现场差旅，后续取消应保留原流水', method: 'cash' }, 200)
  await page.goto(`/erp/projects/${project.id}?tab=finance&section=entries`)
  await openRowAction(page, row(page, `取消已付款费用${suffix}`), '取消费用')
  await reason(page).fill('行程取消，已支付金额转为待退款')
  await submitDialog(page, `business/entries/${expense.id}/cancel-expense/`, 200)
  expect(await admin.get(`/api/business/entries/${expense.id}/`)).toMatchObject({ id: expense.id, cancelled: true, amount: '50.00', credit_amount: '50.00', paid_amount: '50.00', balance: '-50.00' })
  const payments = await admin.get(`/api/business/payments/?entry=${expense.id}`)
  expect(payments.count).toBe(1)
  expect(payments.results[0]).toMatchObject({ id: payment.id, amount: '50.00', reversal_of: null, reversed_by: null })
  await expect(row(page, `取消已付款费用${suffix}`)).toContainText('待退款 50.00')
  await page.screenshot({ path: info.outputPath('cancelled-paid-expense.png'), fullPage: true, animations: 'disabled' })
})
