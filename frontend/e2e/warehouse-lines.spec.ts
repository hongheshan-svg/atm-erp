import { test, expect, api, businessDate, login, openRowAction, searchList, submitDialog, type Page } from './fixtures'
import { selectRemoteOption } from './remote-select-helpers'
const dialog = (page: Page) => page.getByRole('dialog')
const row = (page: Page, text: string) => page.locator('.el-table__body tr:visible').filter({ hasText: text }).first()
test('仓管收货及项目出库展示完整物料资料并逐条保存备注', async ({ page, session }, info) => {
  await login(page, 'admin', process.env.E2E_ADMIN_PASSWORD!)
  const suffix = `${Date.now()}${info.project.name}`
  const admin = await api(page, 'auth/me/')
  const customer = await api(page, 'business/partners/', { kind: 'customer', name: `明细客户${suffix}` }, 201)
  const supplier = await api(page, 'business/partners/', { kind: 'supplier', name: `明细供方${suffix}` }, 201)
  let project = await api(page, 'business/projects/', { name: `明细验收${suffix}`, customer: customer.id, manager: admin.id }, 201)
  let item = await api(page, 'business/items/', { name: `坦克链安装板${suffix}`, specification: '板厚2mm', drawing_number: `A2608-01-00017-${suffix}`, drawing_revision: 'A', brand: '指定品牌', product_category: '12', part_type: 'custom', unit: 'PCS' }, 201)
  const demand = await api(page, `business/projects/${project.id}/demand/`)
  await api(page, `business/projects/${project.id}/revise-bom/`, { expected_revision: demand.revision, lines: [
    { item: item.id, quantity: '2', assembly_unit: '上料单元', change_note: '首版' },
    { item: item.id, quantity: '3', assembly_unit: '下料单元', change_note: '首版' },
  ] })
  const bom = await api(page, `business/projects/${project.id}/demand/`)
  let purchase = await api(page, 'business/purchases/', { project: project.id, supplier: supplier.id, due_date: businessDate(60), lines: bom.lines.map((line: { bom_line: number; quantity: string }) => ({ item: item.id, bom_line: line.bom_line, quantity: line.quantity, unit_price: '10' })) }, 201)
  await api(page, `business/purchases/${purchase.id}/submit/`, {})
  await api(page, `business/purchases/${purchase.id}/approve/`, { reason: '隔离验收管理员审批例外' })
  project = await api(page, `business/projects/${project.id}/`)
  item = await api(page, `business/items/${item.id}/`)
  purchase = await api(page, `business/purchases/${purchase.id}/`)
  const warehouse = await api(page, 'auth/users/', { username: `whdetail${suffix}`, display_name: '仓管验收', roles: ['warehouse'], password: 'Warehouse-Detail-Only-2026' }, 201)
  const wh = await session(warehouse.username, 'Warehouse-Detail-Only-2026')
  await wh.goto('/erp/purchases'); await searchList(wh, '采购订单', purchase.code)
  await openRowAction(wh, row(wh, purchase.code), '收货')
  const table = dialog(wh).getByRole('table', { name: '本次收货明细', exact: true })
  for (const text of ['A2608-01-00017', '版本：A', '品牌：指定品牌', '有图·钣金', '上料单元', '下料单元']) await expect(table).toContainText(text)
  await expect(table.getByRole('columnheader').last()).toHaveText('备注')
  await expect(table).not.toContainText('单价')
  const upper = table.locator('tbody tr').filter({ hasText: '上料单元' })
  const lower = table.locator('tbody tr').filter({ hasText: '下料单元' })
  await upper.getByLabel('数量', { exact: true }).fill('2')
  await upper.getByLabel('备注', { exact: true }).fill('上料板外观合格')
  await lower.getByLabel('数量', { exact: true }).fill('1')
  await lower.getByLabel('不合格隔离数量', { exact: true }).fill('1')
  await lower.getByLabel('备注', { exact: true }).fill('下料板1件孔位待复检')
  await expect(dialog(wh).locator('.warehouse-lines legend')).toContainText(project.code)
  await expect(dialog(wh).locator('.warehouse-summary')).toContainText('已勾选 2/2 行')
  // 正常到货的说明选填，可写送货单号。
  await dialog(wh).getByLabel('送货单号 / 备注', { exact: true }).fill('送货单SH001，按实物分单元收货')
  const viewport = await wh.evaluate(() => ({ body: document.body.scrollWidth, visible: document.documentElement.clientWidth }))
  expect(viewport.body, JSON.stringify(viewport)).toBeLessThanOrEqual(viewport.visible)
  await dialog(wh).locator('.warehouse-scroll').evaluate(el => { el.scrollLeft = 0 })
  await dialog(wh).locator('.action-fields').evaluate(el => { const details = el.querySelector('.warehouse-lines')!; el.scrollTop += details.getBoundingClientRect().top - el.getBoundingClientRect().top })
  if (info.project.name === 'desktop') {
    // 项目号移到表头、资料列合并后，桌面宽度下收货明细不再需要横向滚动，数量输入列直接可见。
    const wrap = dialog(wh).locator('.warehouse-scroll')
    expect(await wrap.evaluate(el => el.scrollWidth - el.clientWidth)).toBeLessThanOrEqual(1)
    await expect(lower.getByLabel('数量', { exact: true })).toBeInViewport()
  }
  await wh.screenshot({ path: info.outputPath('receipt-details.png'), fullPage: true, animations: 'disabled' })
  if (info.project.name === 'desktop') {
    await dialog(wh).locator('.warehouse-scroll').evaluate(el => { el.scrollLeft = el.scrollWidth })
    await wh.screenshot({ path: info.outputPath('receipt-remarks.png'), fullPage: true, animations: 'disabled' })
  }
  await submitDialog(wh, `business/purchases/${purchase.id}/receive/`)
  const moves = await api(wh, `business/moves/?project=${project.id}&kind=receipt`)
  expect(moves.results.map((move: { remark: string }) => move.remark).sort()).toEqual(['上料板外观合格', '下料板1件孔位待复检'].sort())
  expect(moves.results.every((move: object) => !('value' in move))).toBe(true)
  const stock = (await api(wh, `business/stocks/?item=${item.id}`)).results[0]
  expect(stock.quantity).toBe('3.000')
  await wh.goto('/erp/inventory?section=stocks&project=all'); await searchList(wh, '现有库存', item.code)
  await openRowAction(wh, row(wh, item.code), '领料')
  await selectRemoteOption(dialog(wh).getByLabel('项目', { exact: true }), { id: project.id })
  const issueTable = dialog(wh).getByRole('table', { name: '本次出库明细', exact: true })
  await expect(dialog(wh).locator('.warehouse-lines legend')).toContainText(project.code)
  await expect(issueTable).toContainText('A2608-01-00017')
  // 数量与库存列表一致按实际位数显示（5，不再是 5.000）。
  await expect(issueTable.locator('td.col-required_quantity')).toHaveText('5')
  await issueTable.getByLabel('数量', { exact: true }).fill('1')
  await issueTable.getByLabel('备注', { exact: true }).fill('用于上料单元一号工位')
  await dialog(wh).getByLabel('原因 / 说明', { exact: true }).fill('装配领料')
  await dialog(wh).locator('.warehouse-scroll').evaluate(el => { el.scrollLeft = 0 })
  await dialog(wh).locator('.action-fields').evaluate(el => { const details = el.querySelector('.warehouse-lines')!; el.scrollTop += details.getBoundingClientRect().top - el.getBoundingClientRect().top })
  await wh.screenshot({ path: info.outputPath('issue-details.png'), fullPage: true, animations: 'disabled' })
  await submitDialog(wh, 'business/stocks/issue/')
  const issued = (await api(wh, `business/moves/?project=${project.id}&kind=issue`)).results[0]
  expect(issued).toMatchObject({ quantity: '-1.000', remark: '用于上料单元一号工位', reason: '装配领料' })
  expect((await api(wh, `business/stocks/${stock.id}/`)).quantity).toBe('2.000')
  await wh.goto(`/erp/inventory?section=moves&project=${project.id}`)
  await expect(wh.getByText('用于上料单元一号工位', { exact: true })).toBeVisible()
})

test('按 BOM 领料：非标件和标准件分开筛，只领勾选的行，Shift 连续多选', async ({ page, session }, info) => {
  await login(page, 'admin', process.env.E2E_ADMIN_PASSWORD!)
  const suffix = `${Date.now()}${info.project.name}`
  const admin = await api(page, 'auth/me/')
  const customer = await api(page, 'business/partners/', { kind: 'customer', name: `领料筛选客户${suffix}` }, 201)
  const supplier = await api(page, 'business/partners/', { kind: 'supplier', name: `领料筛选供方${suffix}` }, 201)
  const project = await api(page, 'business/projects/', { name: `领料筛选${suffix}`, customer: customer.id, manager: admin.id }, 201)
  const custom = ['底板', '侧板', '压板']
  const standard = ['气缸', '电磁阀']
  // 逐个建料：编码按建料顺序递增，领料表按编码排序，行序与 custom、standard 的顺序一致。
  const items: { id: number }[] = []
  for (const [i, name] of custom.entries()) items.push(await api(page, 'business/items/', { name: `${name}${suffix}`, specification: `6061 板厚${i + 5}mm`, drawing_number: `PICK-${suffix}-${i}`, drawing_revision: 'A', product_category: '11', part_type: 'custom', unit: 'PCS' }, 201))
  for (const name of standard) items.push(await api(page, 'business/items/', { name: `${name}${suffix}`, specification: `SPEC-${name}-${suffix}`, brand: '亚德客', product_category: '21', part_type: 'standard', unit: 'PCS' }, 201))
  const demand = await api(page, `business/projects/${project.id}/demand/`)
  await api(page, `business/projects/${project.id}/revise-bom/`, { expected_revision: demand.revision, lines: items.map(item => ({ item: item.id, quantity: '2', assembly_unit: '上料单元', change_note: '首版' })) })
  const other = await api(page, 'business/projects/', { name: `标准件到货项目${suffix}`, customer: customer.id, manager: admin.id }, 201)
  const { code: ownerCode } = await api(page, `business/projects/${other.id}/`)
  const otherBom = await api(page, `business/projects/${other.id}/demand/`)
  const standardIds = items.slice(custom.length).map(item => item.id)
  await api(page, `business/projects/${other.id}/revise-bom/`, { expected_revision: otherBom.revision, lines: standardIds.map(item => ({ item, quantity: '2' })) })
  for (const owner of [project, other]) {
    const bom = await api(page, `business/projects/${owner.id}/demand/`)
    const lines = bom.lines.filter((line: { item: number }) => owner === other || !standardIds.includes(line.item))
    const purchase = await api(page, 'business/purchases/', { project: owner.id, supplier: supplier.id, due_date: businessDate(30), lines: lines.map((line: { item: number; bom_line: number }) => ({ item: line.item, bom_line: line.bom_line, quantity: '2', unit_price: '10' })) }, 201)
    await api(page, `business/purchases/${purchase.id}/submit/`, {})
    await api(page, `business/purchases/${purchase.id}/approve/`, { reason: '领料筛选验收管理员审批例外' })
    const ordered = await api(page, `business/purchases/${purchase.id}/`)
    await api(page, `business/purchases/${purchase.id}/receive/`, { lines: ordered.lines.map((line: { id: number }) => ({ line: line.id, quantity: '2' })) })
  }
  const warehouse = await api(page, 'auth/users/', { username: `whpick${suffix}`, display_name: '仓管领料', roles: ['warehouse'], password: 'Warehouse-Pick-Only-2026' }, 201)
  const wh = await session(warehouse.username, 'Warehouse-Pick-Only-2026')
  await wh.goto(`/erp/inventory?project=${project.id}&issue=bom`)
  const form = wh.getByRole('dialog', { name: '按 BOM 领料', exact: true })
  const lines = form.locator('.warehouse-lines')
  const summary = lines.locator('.warehouse-summary[role=status]')
  await expect(summary).toContainText('已勾选 0/5 行，本次出库 0')
  const filters = lines.getByRole('group', { name: '按物料类别筛选' }).getByRole('button')
  await expect(filters).toHaveText(['全部 5', '非标件（机加、钣金） 3', '标准件 / 电气件 2'])
  // 默认都不勾，直接提交提示先勾选，不会把几百行一起领出。
  await form.locator('button[type="submit"]').click()
  await expect(form).toContainText('请先勾选本次要领的物料')
  await filters.nth(1).click()
  const rows = lines.locator('tbody tr')
  await expect(rows).toHaveCount(3)
  for (const name of standard) await expect(lines).not.toContainText(`${name}${suffix}`)
  await rows.nth(0).getByRole('checkbox').click()
  await rows.nth(2).getByRole('checkbox').click({ modifiers: ['Shift'] })
  await expect(summary).toContainText('已勾选 3/5 行，本次出库 6')
  await expect(rows.nth(1).getByRole('textbox', { name: /数量/ })).toHaveValue('2.000')
  await filters.nth(2).click()
  await expect(rows).toHaveCount(2)
  await expect(rows.first().getByRole('checkbox')).not.toBeChecked()
  await filters.nth(0).click()
  // 中间一行这次不领：取消勾选，数量清零、不提交。
  await rows.nth(1).getByRole('checkbox').click()
  await expect(summary).toContainText('已勾选 2/5 行，本次出库 4')
  await filters.nth(2).click()
  await rows.nth(0).getByRole('checkbox').click()
  await rows.nth(1).getByRole('checkbox').click()
  await filters.nth(1).click()
  await submitDialog(wh, 'business/stocks/bom-issue/', 409, form)
  await expect(rows).toHaveCount(5)
  for (const [index, name] of standard.entries()) {
    await expect(rows.nth(index)).toHaveClass(/conflict-line/)
    await expect(rows.nth(index).getByRole('checkbox')).toHaveAccessibleName(`本次领用：第 ${4 + index} 行 ${name}${suffix}`)
    await expect(rows.nth(index)).toContainText(ownerCode)
  }
  await form.screenshot({ path: info.outputPath('bom-issue-conflicts.png'), animations: 'disabled' })
  await form.getByRole('button', { name: '取消勾选全部占用行（2）' }).click()
  await expect(summary).toContainText('已勾选 2/5 行，本次出库 4')
  await form.screenshot({ path: info.outputPath('bom-issue-pick.png'), animations: 'disabled' })
  await submitDialog(wh, 'business/stocks/bom-issue/', 200, form)
  const issued = await api(wh, `business/moves/?project=${project.id}&kind=issue`)
  expect(issued.results.map((move: { item_name: string }) => move.item_name).sort()).toEqual([`${custom[0]}${suffix}`, `${custom[2]}${suffix}`].sort())
})
