  expect(await page.locator('.contract-paper table').evaluate(el => el.getBoundingClientRect().width <= el.parentElement!.getBoundingClientRect().width + 1)).toBeTruthy()
  const pdf = await page.pdf({ path: info.outputPath('purchase-contract.pdf'), preferCSSPageSize: true, printBackground: true })
  expect(pdf.subarray(0, 5).toString()).toBe('%PDF-')
