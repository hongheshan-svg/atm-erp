  const signed = await post(`sales/${sale.id}/sign/`, { date: '2026-07-01', manager: user.id, milestones: [{ title: '合同款', amount: '1000', due_date: '2026-12-31' }] })

  await page.goto('/erp/masterdata?section=partners')
