"""运行时依赖固定：requirements.txt 是人工维护的顶层清单，constraints.txt 由 uv 生成并固定全部传递依赖。

只做离线核对（CI 没有 uv，不重新解析）：两份清单版本一致、约束文件可移植，且每条安装路径都应用约束。
"""

import re
import subprocess
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BACKEND = ROOT / 'backend'
# 与 constraints.txt 文件头及 docs/CI_OPERATIONS.md 中的重新生成命令一致。
COMPILE = (
    'uv pip compile --no-config --universal --python-version 3.11 backend/requirements.txt -o backend/constraints.txt'
)
PYTHON = re.search(r'--python-version (\d+)\.(\d+)', COMPILE).groups()
PIN = re.compile(r'^([A-Za-z0-9][A-Za-z0-9._-]*)(\[[^\]]+\])?==([^\s;]+)(?:\s*;\s*(\S.*))?$')
CONSUMER = re.compile(r'requirements(?:-dev|\*)?\.txt')


def normalize(name):
    return re.sub(r'[-_.]+', '-', name).lower()


def lines(path):
    for raw in path.read_text(encoding='utf-8').splitlines():
        line = raw.strip()
        if line and not line.startswith('#'):
            yield line


def constraints():
    """{规范化包名: {版本: 环境标记或 None}}；按平台分叉的包有多个版本。"""
    pins = {}
    for line in lines(BACKEND / 'constraints.txt'):
        match = PIN.match(line)
        if not match or match[2]:
            raise AssertionError(f'constraints.txt 只能包含 name==version[ ; marker]，不能带 extras 或选项：{line}')
        pins.setdefault(normalize(match[1]), {})[match[3]] = match[4]
    return pins


class DependencyPinTests(unittest.TestCase):
    def test_every_top_level_pin_matches_the_constraints(self):
        pins = constraints()
        required = {}
        for line in lines(BACKEND / 'requirements.txt'):
            match = PIN.match(line)
            self.assertTrue(match, f'requirements.txt 须写成 name==version[ ; marker]：{line}')
            required.setdefault(normalize(match[1]), set()).add(match[3])
        for name, versions in required.items():
            # 按平台分别固定的包（带环境标记的多行）在约束文件中也恰好是这几个版本。
            self.assertEqual(
                set(pins.get(name, ())),
                versions,
                f'{name} 与 constraints.txt 不一致：在仓库根目录运行 {COMPILE}，两个文件一并提交',
            )

    def test_constraints_are_generated_and_portable(self):
        text = (BACKEND / 'constraints.txt').read_text(encoding='utf-8')
        self.assertTrue(
            text.startswith('# This file was autogenerated by uv via the following command:\n#    ' + COMPILE + '\n')
        )
        self.assertIn(COMPILE, (ROOT / 'docs/CI_OPERATIONS.md').read_text(encoding='utf-8'))
        # 不得带私有镜像源、本机路径或直接引用，否则其他机器和 CI 无法按同一份清单安装。
        for marker in (
            '://',
            '--index-url',
            '--extra-index-url',
            '--find-links',
            ' @ ',
            '/Users/',
            '/private/',
            '/home/',
            ':\\',
        ):
            self.assertNotIn(marker, text)
        pins = constraints()
        # 约束文件除全部顶层依赖外还须含传递依赖。
        top_level = {normalize(re.match(r'[\w.-]+', line)[0]) for line in lines(BACKEND / 'requirements.txt')}
        self.assertGreater(set(pins), top_level)
        # build_native_wheels 在同一台宿主机上下载两种 CPU 架构的 wheel，pip 按宿主机求值环境标记：
        # 约束只能按操作系统（每个系统在自己的运行器上构建）或解释器区分，不能按 CPU 架构。
        markers = [marker for versions in pins.values() for marker in versions.values() if marker]
        markers += [line.partition(';')[2] for line in lines(BACKEND / 'requirements.txt')]
        for marker in markers:
            self.assertNotRegex(marker, r'platform_machine|platform_release|platform_version')

    def test_dev_requirements_install_under_the_same_constraints(self):
        pins = constraints()
        options = set()
        for line in lines(BACKEND / 'requirements-dev.txt'):
            if line.startswith('-'):
                options.add(line)
                continue
            match = PIN.match(line)
            self.assertTrue(match and not match[4], f'开发依赖须写成 name==version：{line}')
            # 开发工具若也出现在运行时约束中，两处版本必须相同。
            self.assertEqual(set(pins.get(normalize(match[1]), {match[3]: None})), {match[3]}, line)
        self.assertEqual(options, {'-r requirements.txt', '-c constraints.txt'})

    def test_constraints_target_the_shipped_python(self):
        major, minor = PYTHON
        self.assertIn(f'ARG PYTHON_IMAGE=python:{major}.{minor}-', (ROOT / 'docker/app/Dockerfile').read_text())
        for name in ('Dockerfile.tests', 'Dockerfile.native-ota-tests'):
            self.assertIn(f'FROM python:{major}.{minor}-', (ROOT / 'scripts/ci' / name).read_text(), name)
        wheels = (ROOT / 'scripts/ci/build_native_wheels.py').read_text()
        self.assertRegex(wheels, rf"'--python-version',\s*'{major}{minor}'")
        self.assertRegex(wheels, rf"'--abi',\s*'cp{major}{minor}'")
        self.assertIn(f'sys.version_info[:2] != ({major}, {minor})', (ROOT / 'scripts/native_install.py').read_text())
        for workflow in (ROOT / '.github/workflows').glob('*.yml'):
            for version in re.findall(r"python-version: '([^']+)'", workflow.read_text()):
                self.assertEqual(version, f'{major}.{minor}', workflow.name)

    def test_every_install_path_applies_the_constraints(self):
        self.assertIn('-r requirements.txt -c constraints.txt', (ROOT / 'docker/app/Dockerfile').read_text())
        self.assertIn('backend/constraints.txt /tmp/deps/', (ROOT / 'scripts/ci/Dockerfile.tests').read_text())
        self.assertIn("'backend/constraints.txt'", (ROOT / 'scripts/ci/build_native_wheels.py').read_text())
        self.assertIn("'-c', backend / 'constraints.txt'", (ROOT / 'scripts/native_install.py').read_text())
        # 运维范围内凡引用依赖清单的文件（安装、构建、缓存键、影响范围）都须同时引用 constraints.txt；
        # 新增安装路径若只写 requirements.txt，会在这里失败。单测与文档只描述，不安装。
        tracked = subprocess.check_output(['git', 'ls-files'], cwd=ROOT, text=True).splitlines()
        missing = []
        for path in tracked:
            ops = '/' not in path or path.startswith(('scripts/', 'docker/', 'deploy/', '.github/workflows/'))
            if not ops or path.endswith('.md') or path.startswith('scripts/tests/test_') or not (ROOT / path).is_file():
                continue
            text = (ROOT / path).read_text(encoding='utf-8', errors='ignore')
            if CONSUMER.search(text) and 'constraints.txt' not in text:
                missing.append(path)
        self.assertEqual(missing, [])


if __name__ == '__main__':
    unittest.main()
